function renderMarkdownSection() {
  const lines = [
    '## Índice completo: columna `tblLeads` → destino',
    '',
    'Referencia rápida para localizar cada columna de la tabla ancha original en el modelo normalizado.',
    'Vista inversa (reconstruir tblLeads): `v_tblLeads` en TNFG.',
    '',
  ];

  for (const g of TBLLEADS_COLUMN_GROUPS) {
    lines.push(`### ${g.title}`);
    if (g.subtitle) lines.push(`*${g.subtitle}*`, '');
    lines.push('| Columna tblLeads | Destino TNFG | Notas |');
    lines.push('|------------------|-------------------|-------|');
    for (const [src, dest, note] of g.rows) {
      lines.push(`| \`${src}\` | ${dest} | ${note || ''} |`);
    }
    lines.push('');
  }

  return lines.join('\n');
}

